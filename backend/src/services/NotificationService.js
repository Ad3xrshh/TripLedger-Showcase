import pool from '../config/db.js';
import { AppError } from '../utils/AppError.js';
import * as notificationRepository from '../repositories/notificationRepository.js';
import * as BudgetService from '../services/BudgetService.js';
import * as expenseRepository from '../repositories/expenseRepository.js';
import * as tripMemberRepository from '../repositories/tripMemberRepository.js';

// Explicit, closed set of notification types (per Phase 6 spec) rather than
// arbitrary strings scattered across services.
export const NOTIFICATION_TYPES = {
  EXPENSE_CREATED: 'EXPENSE_CREATED',
  EXPENSE_APPROVED: 'EXPENSE_APPROVED',
  EXPENSE_REJECTED: 'EXPENSE_REJECTED',
  EXPENSE_VERIFIED: 'EXPENSE_VERIFIED',
  TRIP_MEMBER_JOINED: 'TRIP_MEMBER_JOINED',
  BUDGET_WARNING: 'BUDGET_WARNING',
  // Phase 8
  SETTLEMENT_FINALIZED: 'SETTLEMENT_FINALIZED',
  TRIP_CLOSED: 'TRIP_CLOSED',
};

/**
 * Writes a single notification. Always called with a `client` from an
 * existing withTransaction block in the service that caused the event
 * (ExpenseService, ExpenseApprovalService, TripService) - never called
 * directly by a GET handler, so notifications are only ever generated by
 * state-changing events, per Phase 6 spec section B4.
 */
export async function notifyUser(client, { userId, tripId, relatedExpenseId, type, message }) {
  return notificationRepository.insertNotification(client, {
    userId,
    tripId,
    relatedExpenseId: relatedExpenseId ?? null,
    type,
    message,
  });
}

/**
 * Added for Phase 6 bugfix (N2). When a member takes an action on an
 * expense (approves/rejects), the EXPENSE_CREATED "needs your review"
 * notification that was sent to them at creation time is now stale for
 * that member specifically - it does not affect the EXPENSE_CREATED
 * notifications still pending for any other member who has not yet acted.
 * Always called with the transaction `client` from the caller, same
 * convention as notifyUser.
 */
export async function clearExpenseCreatedNotification(client, { userId, expenseId }) {
  await notificationRepository.deleteNotificationForUserAndExpense(client, {
    userId,
    relatedExpenseId: expenseId,
    type: NOTIFICATION_TYPES.EXPENSE_CREATED,
  });
}

/**
 * Budget-warning check, reused by both ExpenseService (automatic-mode
 * expenses that verify immediately) and ExpenseApprovalService (expenses
 * that verify on reaching their required approval count). Reuses
 * BudgetService's exported pure `calculateBudgetSummary` - the actual
 * threshold math is never duplicated here.
 *
 * Notifies only the trip owner, and only if they don't already have an
 * unread warning of the same trip pending - this is a deliberately simple
 * dedup rule (see README/final report "known limitations"): it prevents a
 * flood of repeat warnings while the owner hasn't looked at the last one,
 * without needing to track a separate "previous budget status" column.
 */
export async function maybeNotifyBudgetWarning(client, trip) {
  if (trip.budget_type === 'unlimited') return;

  const totalVerifiedMinor = await expenseRepository.sumVerifiedAmountForTrip(client, trip.id);
  let memberCount = null;
  if (trip.budget_type === 'fixed_per_person') {
    memberCount = await tripMemberRepository.countActiveMembers(client, trip.id);
  }

  const summary = BudgetService.calculateBudgetSummary({
    budgetType: trip.budget_type,
    budgetAmountMinor: trip.budget_amount_minor,
    totalVerifiedMinor,
    memberCount,
  });

  if (summary.status !== 'yellow' && summary.status !== 'red') return;

  const owner = await tripMemberRepository.findOwnerMembership(client, trip.id);
  if (!owner) return;

  const alreadyWarned = await notificationRepository.countUnreadOfTypeForUser(
    client,
    owner.user_id,
    trip.id,
    NOTIFICATION_TYPES.BUDGET_WARNING
  );
  if (alreadyWarned > 0) return;

  const label = summary.status === 'red' ? 'over budget' : 'approaching budget';
  await notifyUser(client, {
    userId: owner.user_id,
    tripId: trip.id,
    type: NOTIFICATION_TYPES.BUDGET_WARNING,
    message: `Trip "${trip.name}" is ${label} (${summary.percentageUsed}% of budget used).`,
  });
}

export async function listNotifications(user, { unread, tripId } = {}) {
  const unreadOnly = unread === 'true' || unread === true;
  return notificationRepository.listNotificationsForUser(pool, user.id, { unread: unreadOnly, tripId });
}

export async function getUnreadCount(user, { tripId } = {}) {
  const count = await notificationRepository.countUnreadForUser(pool, user.id, { tripId });
  return { unreadCount: count };
}

async function getOwnedNotificationOrThrow(user, notificationId) {
  const notification = await notificationRepository.findNotificationById(pool, notificationId);
  // Same non-leaking convention as requireTripMembership/getOwnedExpenseOrThrow:
  // a notification that doesn't exist and one that belongs to someone else
  // both return the identical 404.
  if (!notification || notification.user_id !== user.id) {
    throw new AppError('Notification not found', 404, 'NOTIFICATION_NOT_FOUND');
  }
  return notification;
}

export async function markNotificationRead(user, notificationId) {
  await getOwnedNotificationOrThrow(user, notificationId);
  return notificationRepository.markRead(pool, notificationId);
}

export async function markAllNotificationsRead(user, { tripId } = {}) {
  const count = await notificationRepository.markAllReadForUser(pool, user.id, { tripId });
  return { markedRead: count };
}