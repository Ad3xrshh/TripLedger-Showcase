import { AppError } from '../utils/AppError.js';
import * as tripRepository from '../repositories/tripRepository.js';
import * as expenseRepository from '../repositories/expenseRepository.js';
import * as expenseApprovalRepository from '../repositories/expenseApprovalRepository.js';
import * as tripMemberRepository from '../repositories/tripMemberRepository.js';
import * as HistoryService from './HistoryService.js';
import * as NotificationService from './NotificationService.js';
import { assertLedgerIsMutable } from './tripClosure/closureRules.js';

// 9.9.9 Batch 1 issue #7: an approval rule's required_approvals must never
// exceed the number of members who could ever actually approve a given
// expense. Every active member except whichever one turns out to be the
// payer is a potential approver (see approveExpense's CANNOT_SELF_APPROVE
// check - approval eligibility isn't otherwise restricted by role), so
// (active member count - 1) is a hard ceiling that holds regardless of who
// pays. Used both to reject an impossible rule at creation time and to
// clamp calculateRequiredApprovals below so a rule that was valid when
// created can never quietly become impossible if membership shrinks
// afterward.
async function maxPossibleApprovals(poolOrClient, tripId) {
  const activeMemberCount = await tripMemberRepository.countActiveMembers(poolOrClient, tripId);
  return Math.max(0, activeMemberCount - 1);
}

export async function calculateRequiredApprovals(poolOrClient, trip, amountMinor) {
  if (trip.verification_mode === 'automatic') {
    return 0;
  }

  const rule = await expenseApprovalRepository.findApprovalRuleForExpense(poolOrClient, trip.id, amountMinor);

  let required;
  if (trip.verification_mode === 'member_approval') {
    required = rule ? rule.required_approvals : 1;
  } else if (trip.verification_mode === 'tiered') {
    if (!rule) {
      throw new AppError(
        'No approval rule configured for this expense amount in tiered mode',
        400,
        'APPROVAL_RULE_NOT_FOUND'
      );
    }
    required = rule.required_approvals;
  } else {
    required = 1;
  }

  const ceiling = await maxPossibleApprovals(poolOrClient, trip.id);
  return Math.min(required, ceiling);
}

export async function approveExpense(tripMember, expenseId) {
  return withTransaction(async (client) => {
    // 9.9.9 Batch 1 issue #1: the ledger (including approvals) is frozen
    // once closure starts, not just once the trip is fully closed.
    const tripForClosedCheck = await tripRepository.findTripById(client, tripMember.tripId);
    if (tripForClosedCheck) {
      assertLedgerIsMutable(tripForClosedCheck, 'approve expenses');
    }

    const expense = await expenseRepository.findExpenseByIdForUpdate(client, expenseId);
    if (!expense || expense.trip_id !== tripMember.tripId) {
      throw new AppError('Expense not found', 404, 'EXPENSE_NOT_FOUND');
    }

    if (expense.paid_by_member_id === tripMember.id) {
      throw new AppError('Payer cannot approve their own expense', 400, 'CANNOT_SELF_APPROVE');
    }

    if (expense.status === 'verified') {
      throw new AppError('Expense is already verified', 409, 'EXPENSE_ALREADY_VERIFIED');
    }
    if (expense.status === 'rejected') {
      throw new AppError('Expense is already rejected', 409, 'EXPENSE_ALREADY_REJECTED');
    }
    if (expense.status === 'locked') {
      throw new AppError('Expense is locked', 409, 'EXPENSE_LOCKED');
    }
    if (expense.status !== 'pending') {
      throw new AppError(`Expense cannot be approved in state "${expense.status}"`, 409, 'INVALID_EXPENSE_STATUS');
    }

    const existingApproval = await expenseApprovalRepository.findApproval(client, expenseId, tripMember.id);
    if (existingApproval) {
      throw new AppError('You have already approved or rejected this expense', 409, 'ALREADY_APPROVED');
    }

    const trip = await tripRepository.findTripById(client, tripMember.tripId);
    const requiredApprovals = await calculateRequiredApprovals(client, trip, expense.amount_minor);

    await expenseApprovalRepository.insertApproval(client, {
      expenseId,
      memberId: tripMember.id,
      decision: 'approved',
    });

    // Phase 6 bugfix (N2): the approver had an EXPENSE_CREATED "needs your
    // review" notification for this expense from when it was created. Now
    // that they've acted on it, that notification is stale for them
    // specifically - clear it so it doesn't linger in their inbox and get
    // mistaken for a notification generated by their own approval action.
    // This does not touch EXPENSE_CREATED notifications for any other
    // member who has not yet acted, and does not touch any other
    // notification type.
    const actingMember = await tripMemberRepository.findMemberById(client, tripMember.id);
    if (actingMember) {
      await NotificationService.clearExpenseCreatedNotification(client, {
        userId: actingMember.user_id,
        expenseId,
      });
    }

    const approvedCount = await expenseApprovalRepository.countApprovals(client, expenseId, 'approved');

    let updatedExpense = expense;
    const justVerified = approvedCount >= requiredApprovals;
    if (justVerified) {
      updatedExpense = await expenseRepository.updateExpenseStatus(client, expenseId, 'verified');
    }

    // Phase 6: history + notifications, inside the same transaction so they
    // roll back together with the approval if anything above fails.
    await HistoryService.recordEvent(client, {
      tripId: trip.id,
      actorMemberId: tripMember.id,
      entityType: 'expense',
      entityId: expenseId,
      action: 'expense_approved',
      metadata: { approvedCount, requiredApprovals },
    });

    const payerMember = await tripMemberRepository.findMemberById(client, expense.paid_by_member_id);
    if (payerMember) {
      if (justVerified) {
        // Send only the verified notification, not a separate "approved"
        // one - a single approval action shouldn't produce two
        // notifications for the same underlying event (spec section B6).
        await HistoryService.recordEvent(client, {
          tripId: trip.id,
          actorMemberId: tripMember.id,
          entityType: 'expense',
          entityId: expenseId,
          action: 'expense_verified',
          metadata: { approvedCount, requiredApprovals },
        });
        await NotificationService.notifyUser(client, {
          userId: payerMember.user_id,
          tripId: trip.id,
          relatedExpenseId: expenseId,
          type: NotificationService.NOTIFICATION_TYPES.EXPENSE_VERIFIED,
          message: `Your expense "${expense.description}" has been verified.`,
        });
        await NotificationService.maybeNotifyBudgetWarning(client, trip);
      } else {
        await NotificationService.notifyUser(client, {
          userId: payerMember.user_id,
          tripId: trip.id,
          relatedExpenseId: expenseId,
          type: NotificationService.NOTIFICATION_TYPES.EXPENSE_APPROVED,
          message: `Your expense "${expense.description}" received an approval (${approvedCount}/${requiredApprovals}).`,
        });
      }
    }

    const verificationDetails = await buildVerificationDetails(client, trip, updatedExpense, tripMember.id);

    return {
      expense: updatedExpense,
      verification: verificationDetails,
    };
  });
}

export async function rejectExpense(tripMember, expenseId, reason) {
  return withTransaction(async (client) => {
    // 9.9.9 Batch 1 issue #1: same ledger-freeze rule as approveExpense.
    const tripForClosedCheck = await tripRepository.findTripById(client, tripMember.tripId);
    if (tripForClosedCheck) {
      assertLedgerIsMutable(tripForClosedCheck, 'reject expenses');
    }

    const expense = await expenseRepository.findExpenseByIdForUpdate(client, expenseId);
    if (!expense || expense.trip_id !== tripMember.tripId) {
      throw new AppError('Expense not found', 404, 'EXPENSE_NOT_FOUND');
    }

    if (expense.status === 'verified') {
      throw new AppError('Expense is already verified', 409, 'EXPENSE_ALREADY_VERIFIED');
    }
    if (expense.status === 'rejected') {
      throw new AppError('Expense is already rejected', 409, 'EXPENSE_ALREADY_REJECTED');
    }
    if (expense.status === 'locked') {
      throw new AppError('Expense is locked', 409, 'EXPENSE_LOCKED');
    }
    if (expense.status !== 'pending') {
      throw new AppError(`Expense cannot be rejected in state "${expense.status}"`, 409, 'INVALID_EXPENSE_STATUS');
    }

    // Deliberately no self-reject guard here (unlike CANNOT_SELF_APPROVE above):
    // self-approval is blocked because the payer can't independently validate
    // their own financial claim, but self-rejection is the payer withdrawing
    // their own submission, which is a different, permitted action.

    const existingApproval = await expenseApprovalRepository.findApproval(client, expenseId, tripMember.id);
    if (!existingApproval) {
      await expenseApprovalRepository.insertApproval(client, {
        expenseId,
        memberId: tripMember.id,
        decision: 'rejected',
      });
    } else if (existingApproval.decision !== 'rejected') {
      // Member previously approved (or otherwise has a non-rejected record)
      // and is now rejecting. Update the existing row in place rather than
      // inserting a second one, since (expense_id, approved_by_member_id) is
      // unique - otherwise the row would stay stuck at decision='approved'
      // even though the expense ends up rejected, producing a misleading
      // audit trail.
      await expenseApprovalRepository.updateApprovalDecision(client, {
        expenseId,
        memberId: tripMember.id,
        decision: 'rejected',
      });
    }

    const updatedExpense = await expenseRepository.updateExpenseStatus(client, expenseId, 'rejected');

    const trip = await tripRepository.findTripById(client, tripMember.tripId);

    // Phase 6: history + notification, inside the same transaction.
    await HistoryService.recordEvent(client, {
      tripId: trip.id,
      actorMemberId: tripMember.id,
      entityType: 'expense',
      entityId: expenseId,
      action: 'expense_rejected',
      metadata: { reason: reason ?? null },
    });

    // Skip notifying the payer if they rejected their own expense
    // (withdrawing their own submission is a permitted action per the
    // comment above - it's not news to them).
    if (expense.paid_by_member_id !== tripMember.id) {
      const payerMember = await tripMemberRepository.findMemberById(client, expense.paid_by_member_id);
      if (payerMember) {
        await NotificationService.notifyUser(client, {
          userId: payerMember.user_id,
          tripId: trip.id,
          relatedExpenseId: expenseId,
          type: NotificationService.NOTIFICATION_TYPES.EXPENSE_REJECTED,
          message: `Your expense "${expense.description}" was rejected.`,
        });
      }
    }

    const verificationDetails = await buildVerificationDetails(client, trip, updatedExpense, tripMember.id);

    return {
      expense: updatedExpense,
      verification: verificationDetails,
    };
  });
}

export async function createApprovalRule(tripMember, { minAmountMinor, maxAmountMinor, requiredApprovals }) {
  if (tripMember.role !== 'owner' && tripMember.role !== 'admin') {
    throw new AppError('Only trip owners or admins can configure approval rules', 403, 'FORBIDDEN');
  }

  return withTransaction(async (client) => {
    // Row-lock the trip so two concurrent rule-creation requests for the
    // same trip can't both pass the overlap check against the same
    // pre-insert snapshot of existing rules.
    const trip = await tripRepository.findTripByIdForUpdate(client, tripMember.tripId);
    if (!trip) {
      throw new AppError('Trip not found', 404, 'TRIP_NOT_FOUND');
    }
    // 9.9.9 Batch 1 issue #1: approval configuration is part of the ledger
    // and is frozen during closure, not just once fully closed.
    assertLedgerIsMutable(trip, 'change approval rules');

    // 9.9.9 Batch 1 issue #7: reject a rule that could never be satisfied
    // under current membership up front, rather than letting it silently
    // create an unverifiable expense later. calculateRequiredApprovals'
    // own clamp is the safety net if membership shrinks after this point.
    const ceiling = await maxPossibleApprovals(client, tripMember.tripId);
    if (requiredApprovals > ceiling) {
      throw new AppError(
        `requiredApprovals (${requiredApprovals}) can never be satisfied - this trip currently has at most ${ceiling} possible approvers for any single expense (every active member except whoever pays)`,
        422,
        'APPROVAL_REQUIREMENT_IMPOSSIBLE'
      );
    }

    const existingRules = await expenseApprovalRepository.listApprovalRulesForTrip(client, tripMember.tripId);

    const newMax = maxAmountMinor ?? Infinity;
    const overlaps = existingRules.some((rule) => {
      const existingMin = rule.min_amount_minor;
      const existingMax = rule.max_amount_minor == null ? Infinity : rule.max_amount_minor;
      // Two ranges [a, b] and [c, d] overlap iff a <= d && c <= b.
      return minAmountMinor <= existingMax && existingMin <= newMax;
    });

    if (overlaps) {
      throw new AppError(
        'This amount range overlaps with an existing approval rule for this trip',
        409,
        'APPROVAL_RULE_OVERLAP'
      );
    }

    const rule = await expenseApprovalRepository.insertApprovalRule(client, {
      tripId: tripMember.tripId,
      minAmountMinor,
      maxAmountMinor: maxAmountMinor ?? null,
      requiredApprovals,
    });

    return rule;
  });
}

export async function listApprovalRules(tripMember) {
  return expenseApprovalRepository.listApprovalRulesForTrip(pool, tripMember.tripId);
}

export async function getVerificationDetails(tripMember, expenseId) {
  const expense = await expenseRepository.findExpenseById(pool, expenseId);
  if (!expense || expense.trip_id !== tripMember.tripId) {
    throw new AppError('Expense not found', 404, 'EXPENSE_NOT_FOUND');
  }

  const trip = await tripRepository.findTripById(pool, tripMember.tripId);
  return buildVerificationDetails(pool, trip, expense, tripMember.id);
}

async function buildVerificationDetails(poolOrClient, trip, expense, currentMemberId) {
  const requiredApprovals = await calculateRequiredApprovals(poolOrClient, trip, expense.amount_minor);
  const approvals = await expenseApprovalRepository.listApprovalsForExpense(poolOrClient, expense.id);

  const approvedList = approvals.filter((a) => a.decision === 'approved');
  const received = approvedList.length;
  const remaining = Math.max(0, requiredApprovals - received);
  const currentUserApproved = approvedList.some((a) => a.member_id === currentMemberId);

  return {
    expenseId: expense.id,
    status: expense.status,
    verificationMode: trip.verification_mode,
    approvalsRequired: requiredApprovals,
    approvalsReceived: received,
    approvalsRemaining: remaining,
    approvedBy: approvedList.map((a) => ({
      memberId: a.member_id,
      displayName: a.display_name,
      approvedAt: a.approved_at,
    })),
    currentUserApproved,
  };
}